// in the same shape as the 5x7 font's file: seven rows of five, separated by spaces
export const FONT_SMALL = Object.fromEntries(Object.entries(G).map(([ch, s]) => {
  const rows = s.split(" ").map((r) => r.padEnd(5, "."))
  while (rows.length < 7) rows.push(".....")
  return [ch, rows.join(" ")]
}))
